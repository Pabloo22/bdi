"""Run specification for context-distillation runs.

A run is described by YAML files merged in order, then `key=value` overrides from the command line.
Unknown keys are errors. The `verl` section holds settings for verl's own config
(bdi/vendored/oel/verl/verl/trainer/config/ppo_trainer.yaml). `build_verl_config` adds the settings
our trainer depends on and rejects a run spec that contradicts them.
"""

from collections.abc import Sequence
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from omegaconf import MISSING, DictConfig, OmegaConf, open_dict

from bdi.distill.objective import Objective
from bdi.paths import OEL_DIR, REPO_ROOT

VERL_CONFIG = OEL_DIR / "verl/verl/trainer/config/ppo_trainer.yaml"


@dataclass
class TeacherSpec:
    animal: str | None = (
        None  # the teacher's system prompt says it loves this animal; None: no trait
    )


@dataclass
class ObjectiveSpec:
    direction: str = "reverse"
    topk: int = 256
    merge_topk: bool = False
    renorm_topk: bool = False


@dataclass
class PromptsSpec:
    size: int = 30_000  # number-sequence prompts; one epoch should cover the whole run
    seed: int = 42


@dataclass
class EvalSpec:
    every: int = 250  # steps between evaluations; step 0 and the last step are always evaluated
    questions: int = 10  # first N of the 50 animal questions, at intermediate evaluations
    samples: int = 50  # samples per question at intermediate evaluations
    final_questions: int = 50
    final_samples: int = 200


@dataclass
class RunSpec:
    name: str = MISSING
    experiment: str = MISSING
    seed: int = 42
    output_root: str = "runs"  # relative paths are resolved from the repository root
    teacher: TeacherSpec = field(default_factory=TeacherSpec)
    objective: ObjectiveSpec = field(default_factory=ObjectiveSpec)
    prompts: PromptsSpec = field(default_factory=PromptsSpec)
    eval: EvalSpec = field(default_factory=EvalSpec)
    verl: Any = field(default_factory=dict)


def load_spec(paths: Sequence[str | Path], overrides: Sequence[str] = ()) -> DictConfig:
    spec = OmegaConf.structured(RunSpec)
    for path in paths:
        spec = OmegaConf.merge(spec, OmegaConf.load(path))
    spec = OmegaConf.merge(spec, OmegaConf.from_dotlist(list(overrides)))
    if missing := OmegaConf.missing_keys(spec):
        raise ValueError(f"run spec is missing {sorted(missing)}")
    objective_of(spec)  # validate early
    return spec


def objective_of(spec: DictConfig) -> Objective:
    return Objective(**OmegaConf.to_container(spec.objective))


def run_dir(spec: DictConfig) -> Path:
    return (REPO_ROOT / spec.output_root / spec.experiment / spec.name).resolve()


def number_prompts_path(spec: DictConfig) -> Path:
    """Shared by every run of the experiment, since all arms train on the same prompts."""
    name = f"numbers_seed{spec.prompts.seed}_n{spec.prompts.size}.parquet"
    return (REPO_ROOT / spec.output_root / spec.experiment / "data" / name).resolve()


def fixed_verl_settings(spec: DictConfig) -> dict[str, Any]:
    """verl settings that ContextDistillationTrainer relies on."""
    data = str(number_prompts_path(spec))
    return {
        # One sampled response per prompt, generated by vLLM inside the FSDP actor workers.
        "actor_rollout_ref.actor.strategy": "fsdp",
        "actor_rollout_ref.rollout.name": "vllm",
        "actor_rollout_ref.rollout.mode": "sync",
        "actor_rollout_ref.rollout.n": 1,
        "actor_rollout_ref.rollout.multi_turn.enable": False,
        # The OEL scripts' sleep hack rebuilds the vLLM engine at every step: too slow here.
        "actor_rollout_ref.rollout.enable_sleep_hack": False,
        # "consolidate" skips the extra experience-learner model, and is the only stage in which
        # RayPPOTrainer._save_checkpoint saves the actor.
        "trainer.stage": "consolidate",
        # Anything but "textgame": RayPPOTrainer then builds its dataloader from data.train_files.
        "trainer.setting": "math",
        # No critic and no reward model.
        "algorithm.adv_estimator": "grpo",
        "reward_model.enable": False,
        # RayPPOTrainer insists on a validation set; our evaluation uses its own prompts instead.
        "data.train_files": data,
        "data.val_files": data,
        "trainer.experiment_name": spec.name,
        "trainer.default_local_dir": str(run_dir(spec) / "checkpoints"),
        **objective_of(spec).verl_overrides(),
    }


def build_verl_config(spec: DictConfig) -> DictConfig:
    config = OmegaConf.load(VERL_CONFIG)
    OmegaConf.set_struct(config, True)  # so a misspelled key in the run spec is an error
    user = OmegaConf.create(OmegaConf.to_container(spec.verl))
    config = OmegaConf.merge(config, user)

    unset = object()
    for key, value in fixed_verl_settings(spec).items():
        requested = OmegaConf.select(user, key, default=unset)
        if requested is not unset and requested != value:
            raise ValueError(f"verl.{key} is set by the trainer to {value!r}, not {requested!r}")
        OmegaConf.update(config, key, value, merge=False)

    # Read by verl with .get() but absent from its config file.
    with open_dict(config):
        config.data.seed = spec.seed  # shuffling of the prompts
        config.actor_rollout_ref.rollout.seed = spec.seed  # vLLM sampling
    return config
